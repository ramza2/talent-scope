#!/usr/bin/env bash
set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMPOSE_FILE="${ROOT_DIR}/docker-compose.server.yml"
ENV_FILE="${ROOT_DIR}/.env.server"
ENV_EXAMPLE="${ROOT_DIR}/.env.server.example"

usage() {
  cat <<'EOF'
TalentScope server deploy helper

Usage:
  ./scripts/deploy.sh [options]

Options:
  --configure       Recreate .env.server interactively even if it exists
  --test            Run isolated server-side pytest after deployment
  --perf            Prepare PERF DB and run 2k benchmark/recall/runtime EXPLAIN
  --no-build        Skip production application image build (--test still refreshes test image)
  -h, --help        Show this help

Default behavior:
  - If .env.server does not exist, create it interactively.
  - Blank answers use the shown default.
  - APP_SECRET_KEY / PostgreSQL password / MinIO password are generated
    automatically when left blank.
  - Existing .env.server is reused unless --configure is specified.
EOF
}

FORCE_CONFIGURE=0
RUN_TESTS=0
RUN_PERF=0
DO_BUILD=1

while [[ $# -gt 0 ]]; do
  case "$1" in
    --configure) FORCE_CONFIGURE=1 ;;
    --test) RUN_TESTS=1 ;;
    --perf) RUN_PERF=1 ;;
    --no-build) DO_BUILD=0 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

log() { printf '\n==> %s\n' "$*"; }
die() { echo "ERROR: $*" >&2; exit 1; }

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "Required command not found: $1"
}

random_hex() {
  local bytes="${1:-32}"
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$bytes"
  elif [[ -r /dev/urandom ]]; then
    od -An -N"$bytes" -tx1 /dev/urandom | tr -d ' \n'
  else
    die "Cannot generate secure random value (openssl or /dev/urandom required)"
  fi
}

prompt_default() {
  local __var="$1" label="$2" default="$3" input
  read -r -p "${label} [${default}]: " input || true
  printf -v "$__var" '%s' "${input:-$default}"
}

prompt_optional() {
  local __var="$1" label="$2" input
  read -r -p "${label} (optional, Enter = empty): " input || true
  printf -v "$__var" '%s' "$input"
}

prompt_secret_or_generate() {
  local __var="$1" label="$2" generated input
  generated="$(random_hex 24)"
  read -r -s -p "${label} (Enter = auto-generate): " input || true
  printf '\n'
  printf -v "$__var" '%s' "${input:-$generated}"
}

write_env() {
  local tmp
  tmp="$(mktemp "${ROOT_DIR}/.env.server.tmp.XXXXXX")"
  chmod 600 "$tmp"
  cat >"$tmp" <<EOF
# Generated by scripts/deploy.sh. Do not commit.
TALENTSCOPE_HOST=${TALENTSCOPE_HOST}
TRAEFIK_NETWORK=${TRAEFIK_NETWORK}
TRAEFIK_ENTRYPOINT=${TRAEFIK_ENTRYPOINT}
TRAEFIK_CERTRESOLVER=${TRAEFIK_CERTRESOLVER}

APP_ENV=production
APP_SECRET_KEY=${APP_SECRET_KEY}
SESSION_COOKIE_NAME=${SESSION_COOKIE_NAME}
SESSION_TTL_SECONDS=${SESSION_TTL_SECONDS}
CSRF_COOKIE_NAME=${CSRF_COOKIE_NAME}
REDIS_KEY_PREFIX=${REDIS_KEY_PREFIX}

POSTGRES_DB=${POSTGRES_DB}
POSTGRES_USER=${POSTGRES_USER}
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
POSTGRES_TEST_DB=${POSTGRES_TEST_DB}
POSTGRES_PERF_DB=${POSTGRES_PERF_DB}

MINIO_ROOT_USER=${MINIO_ROOT_USER}
MINIO_ROOT_PASSWORD=${MINIO_ROOT_PASSWORD}
S3_ACCESS_KEY=${MINIO_ROOT_USER}
S3_SECRET_KEY=${MINIO_ROOT_PASSWORD}
S3_BUCKET=${S3_BUCKET}

UPLOAD_MAX_FILE_SIZE_MB=50
UPLOAD_MAX_FILES_PER_SESSION=20
UPLOAD_SESSION_TTL_HOURS=24
LIBREOFFICE_BIN=soffice
LIBREOFFICE_TIMEOUT_SECONDS=120

LLM_BASE_URL=${LLM_BASE_URL}
LLM_API_KEY=${LLM_API_KEY}
LLM_MODEL=${LLM_MODEL}
VLM_BASE_URL=${VLM_BASE_URL}
VLM_API_KEY=${VLM_API_KEY}
VLM_MODEL=${VLM_MODEL}

AI_REQUEST_TIMEOUT_SECONDS=60
IDENTIFY_MAX_PAGES=5
IDENTIFY_MAX_VLM_PAGES=3
IDENTIFY_MAX_TEXT_CHARS=20000
IDENTIFY_PDF_RENDER_DPI=120
